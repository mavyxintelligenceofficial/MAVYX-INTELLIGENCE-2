"""
AI Performance Evaluator — measures recommendation quality.

Per Volume IV Chapter 5: Learning Intelligence
- Section 5.4: Recommendation Outcome Evaluation
- Section 5.5: Confidence Calibration
- Section 5.6: Specialist Agent Performance Evaluation
- Section 5.12: AI Quality Metrics

This module evaluates past recommendations against actual market
outcomes to measure accuracy and improve confidence calibration.
"""

import json
import logging
from datetime import datetime, timezone
from typing import Any, Optional

logger = logging.getLogger(__name__)


class PerformanceEvaluator:
    """Evaluates AI recommendation quality over time.

    Per Vol. IV §5.4: "Every recommendation generated by the Executive
    Decision Engine shall be evaluated against subsequent market behavior."
    """

    def __init__(self, store: Any = None, market_fetcher: Any = None):
        self.store = store
        self.market_fetcher = market_fetcher

    async def evaluate_recommendation(
        self,
        analysis_id: str,
        current_price: float,
    ) -> dict[str, Any]:
        """Evaluate a past recommendation against current market price.

        Per Vol. IV §5.4, evaluation considers:
        - Directional accuracy
        - Timing accuracy
        - Entry quality
        - Risk-adjusted performance
        """
        if not self.store:
            return {"error": "Store not available"}

        analysis = self.store.get_by_id(analysis_id)
        if not analysis:
            return {"error": "Analysis not found"}

        recommendation = analysis.get("recommendation", "wait")
        suggested_action = analysis.get("suggested_action", {})
        entry_zone = suggested_action.get("entry_zone", "N/A")

        # Determine if the recommendation was directionally correct
        outcome = self._assess_outcome(recommendation, entry_zone, current_price)

        return {
            "analysis_id": analysis_id,
            "symbol": analysis.get("symbol"),
            "original_recommendation": recommendation,
            "original_confidence": analysis.get("confidence"),
            "current_price": current_price,
            "outcome": outcome,
            "evaluated_at": datetime.now(timezone.utc).isoformat(),
        }

    def _assess_outcome(
        self, recommendation: str, entry_zone: str, current_price: float
    ) -> str:
        """Classify recommendation outcome.

        Per Vol. IV §5.4 categories:
        - Successful
        - Partially Successful
        - Neutral
        - Unsuccessful
        - Invalidated by Market Conditions
        """
        if recommendation in ("wait", "no_trade"):
            return "neutral"

        # Try to parse entry zone
        try:
            if "-" in str(entry_zone):
                parts = str(entry_zone).replace(" ", "").split("-")
                low = float(parts[0])
                high = float(parts[1])
                in_zone = low <= current_price <= high
            else:
                in_zone = True  # Can't parse, assume ok

            if recommendation == "buy":
                # For buy, price should be at or below entry
                return "successful" if current_price <= float(entry_zone.split("-")[0].strip()) else "partially_successful"
            elif recommendation == "sell":
                # For sell, price should be at or above entry
                return "successful" if current_price >= float(entry_zone.split("-")[-1].strip()) else "partially_successful"
        except (ValueError, IndexError):
            pass

        return "needs_review"

    def calculate_system_metrics(
        self, analyses: list[dict]
    ) -> dict[str, Any]:
        """Calculate overall system quality metrics.

        Per Vol. IV §5.12: AI Quality Metrics
        """
        if not analyses:
            return {"total_analyses": 0}

        total = len(analyses)
        recommendations = [a.get("recommendation") for a in analyses]
        confidences = [a.get("confidence", 0) for a in analyses]

        return {
            "total_analyses": total,
            "recommendation_distribution": {
                "buy": recommendations.count("buy"),
                "sell": recommendations.count("sell"),
                "wait": recommendations.count("wait"),
                "no_trade": recommendations.count("no_trade"),
            },
            "average_confidence": round(sum(confidences) / total, 1),
            "confidence_range": {
                "min": min(confidences),
                "max": max(confidences),
            },
            "symbols_analyzed": len(set(a.get("symbol") for a in analyses)),
        }

    def get_agent_performance(self, analyses: list[dict]) -> dict[str, Any]:
        """Analyze individual agent performance.

        Per Vol. IV §5.6: "Each specialist AI agent shall maintain
        an independent performance profile."
        """
        agent_stats: dict[str, dict] = {}

        for analysis in analyses:
            for agent in analysis.get("agent_breakdown", []):
                agent_id = agent.get("agent_id", "unknown")
                if agent_id not in agent_stats:
                    agent_stats[agent_id] = {
                        "total_analyses": 0,
                        "signals": {"bullish": 0, "bearish": 0, "neutral": 0},
                        "avg_confidence": [],
                    }

                stats = agent_stats[agent_id]
                stats["total_analyses"] += 1
                signal = agent.get("signal", "neutral")
                if signal in stats["signals"]:
                    stats["signals"][signal] += 1
                stats["avg_confidence"].append(agent.get("confidence", 0))

        # Calculate averages
        for agent_id, stats in agent_stats.items():
            confidences = stats["avg_confidence"]
            stats["avg_confidence"] = round(
                sum(confidences) / len(confidences), 1
            ) if confidences else 0

        return agent_stats
